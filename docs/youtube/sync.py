#!/usr/bin/env python3
"""Turn record-install.sh markers into exact video times.

    python3 docs/youtube/sync.py DEMO.mp4 MARKERS.txt [TIMELINE.env]

The markers are device-clock epochs taken while recording.  The video starts
somewhere after the `record_start` marker (encoder startup), so one visual event
calibrates the difference: the app launch changes the screen from Termux to the
app, and we know exactly when we asked for that.  Everything else is then
offset by the same amount.

Prints a table and, if a path is given, writes the variables that
build-short-install.sh reads.
"""

import re
import subprocess
import sys
from pathlib import Path

MARKER = re.compile(r"^(\d+\.\d+) (\S+)$")
LOGCAT = re.compile(r"^\s*(\d+\.\d+)\s+\d+\s+\d+\s+[IWE]\s+FreebuffNative:\s*(.*)$")


def load(path):
    events = []
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        m = MARKER.match(line)
        if m:
            events.append((float(m.group(1)), m.group(2)))
            continue
        m = LOGCAT.match(line)
        if m:
            events.append((float(m.group(1)), "log:" + m.group(2)[:60]))
    return events


def scene_times(video):
    """Times (seconds) where the picture changes abruptly."""
    proc = subprocess.run(
        ["ffmpeg", "-hide_banner", "-i", str(video), "-vf",
         "select='gt(scene,0.2)',metadata=print", "-f", "null", "-"],
        capture_output=True, text=True, check=False)
    return [float(v) for v in re.findall(r"pts_time:([0-9.]+)", proc.stderr)]


def duration(video):
    proc = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", str(video)],
        capture_output=True, text=True, check=False)
    return float(proc.stdout.strip() or 0)


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    video = Path(sys.argv[1])
    markers = Path(sys.argv[2])
    timeline = Path(sys.argv[3]) if len(sys.argv) > 3 else None

    events = load(markers)
    times = {name: epoch for epoch, name in events if not name.startswith("log:")}
    for epoch, name in events:
        if name.startswith("log:"):
            times.setdefault("log_result", epoch)

    if "record_start" not in times or "app_launch" not in times:
        raise SystemExit("markers are missing record_start/app_launch")

    zero = times["record_start"]
    predicted = times["app_launch"] - zero
    scenes = scene_times(video)
    near = [s for s in scenes if abs(s - predicted) <= 2.5]
    offset = (near[0] - predicted) if near else 0.0
    if not near:
        print("warning: no scene change near the app launch; offset set to 0")

    def at(name, default=None):
        if name not in times:
            return default
        return round(times[name] - zero + offset, 3)

    total = duration(video)
    print("video      %s (%.2fs)" % (video.name, total))
    print("offset     %+.3fs (encoder start + capture)" % offset)
    for name in sorted(times, key=lambda n: times[n]):
        if name.startswith("log:"):
            continue
        print("  %-18s %7.3fs" % (name, times[name] - zero + offset))

    # One continuous install segment: every frame between the keyboard going
    # away and the wrapper landing stays in, so nothing is cut out.  The build
    # compresses it to the target length instead of dropping material.
    install_in = (at("keyboard_dismissed") or at("setup_tap", 0)) + 0.4
    install_out = min(at("wrapper_appeared", total) + 2.5, total - 0.5)
    plan = {
        "APP_IN": at("app_launch", 0) + 0.8,
        "APP_OUT": min(at("dialog_tap", total) - 0.1, at("app_launch", 0) + 3.0),
        "DIALOG_IN": at("dialog_tap", 0) + 0.25,
        "DIALOG_OUT": min(at("setup_tap", total) - 0.2, at("dialog_tap", 0) + 3.2),
        "INSTALL_IN": install_in,
        "INSTALL_SPLIT": max(install_in + 1.0, at("binary_appeared", install_out) - 2.0),
        "INSTALL_OUT": install_out,
        "REP_IN": at("check_tap", 0) + 1.0,
        "REP_OUT": min(at("report_shown", total) + 2.6, total - 0.4),
    }
    print("\ncut plan")
    for key, value in plan.items():
        print("  %-10s %7.2f" % (key, value))

    if timeline:
        lines = ["# generated by sync.py; video: %s" % video.name]
        lines += ["%s=%.2f" % (key, value) for key, value in plan.items()]
        timeline.write_text("\n".join(lines) + "\n")
        print("\nwrote " + str(timeline))


if __name__ == "__main__":
    sys.exit(main())
